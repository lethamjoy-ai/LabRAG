"""Read-only presentation views. No execution, scoring or provider calls."""
import json
from pathlib import Path
import pandas as pd
import streamlit as st


def question_views(run, questions=None):
    questions=questions or {}
    records={(r['question_id'],r['configuration']):r for r in run.get('records',[])}
    parameters=run.get('parameters',{})
    ids=parameters.get('question_ids')
    configs=parameters.get('configurations')
    pairs=list(records) if ids is None or configs is None else [(q,c) for q in ids for c in configs]
    pairs+= [pair for pair in records if pair not in pairs]
    output=[]
    for identifier,variant in pairs:
        record=records.get((identifier,variant))
        reference=questions.get(identifier,{})
        row=record or {'question_id':identifier,'configuration':variant,'status':'Pending / Missing',
                       'question':reference.get('question','Question text not recorded in available matching data')}
        facts=row.get('verified_required_facts') or row.get('expected_facts') or reference.get('expected_facts')
        expected=row.get('expected_answer') or ('; '.join(str(f) for f in facts) if isinstance(facts,list) else facts)
        quality=row.get('answer_quality') or {}
        answer=row.get('answer')
        if not record:answer='Not executed — pending'
        elif parameters.get('mode')=='retrieval':answer='Not generated — retrieval-only mode'
        elif not answer:answer='Not generated — excluded' if row.get('status')=='Excluded' else 'No answer recorded'
        output.append({'Question ID':identifier,'Question':row.get('question',reference.get('question','Not recorded')),
            'Variant':variant,'Evaluation status':row.get('status','Not recorded'),'Generated answer':answer,
            'Expected answer':expected or 'Not recorded','Correctness':(quality.get('correctness') or {}).get('score'),
            'Faithfulness':(quality.get('faithfulness') or {}).get('score'),'_record':row,'_reference':reference})
    return output


def render_overview(run):
    st.subheader('Evaluation Overview')
    params=run.get('parameters',{});rows=run.get('records',[])
    total=len(params['question_ids'])*len(params['configurations']) if 'question_ids' in params and 'configurations' in params else None
    completed=sum(r.get('status')=='Completed' for r in rows)
    excluded=sum(r.get('status')=='Excluded' for r in rows)
    values={'Total evaluation pairs':total,'Completed pairs':completed,
        'Failed pairs':sum(r.get('status')=='Failed' for r in rows),
        'Missing pairs':max(0,total-len(rows)) if total is not None else None,
        'Remaining pairs':max(0,total-completed-excluded) if total is not None else None,
        'Current evaluation status':run.get('status','Not recorded')}
    for start in (0,3):
        for column,(label,value) in zip(st.columns(3),list(values.items())[start:start+3]):
            column.metric(label,'Not recorded' if value is None else value)
    st.caption(f"Saved run: {run.get('run_id','Unknown')} · Excluded pairs: {excluded}. Remaining includes failed and other unfinished pairs. Missing results are never generated by this dashboard.")


def render_questions(run,questions):
    st.subheader('Evaluated Questions')
    views=question_views(run,questions)
    if not views:
        st.info('No question selection or saved records are available.');return
    search=st.text_input('Search evaluated questions',placeholder='Question ID, test name, question or answer')
    left,right=st.columns(2)
    variants=left.multiselect('Filter variants',list(dict.fromkeys(r['Variant'] for r in views)))
    statuses=right.multiselect('Filter evaluation status',list(dict.fromkeys(r['Evaluation status'] for r in views)))
    shown=[r for r in views if (not variants or r['Variant'] in variants) and (not statuses or r['Evaluation status'] in statuses)
        and (not search or search.casefold() in ' '.join(str(v) for k,v in r.items() if not k.startswith('_')).casefold())]
    st.caption(f'{len(shown)} of {len(views)} selected question/variant pairs. Blank scores mean unmeasured; pending pairs are not failures.')
    st.dataframe(pd.DataFrame([{k:v for k,v in r.items() if not k.startswith('_')} for r in shown]),use_container_width=True,hide_index=True)
    if not shown:return
    lookup={f"{r['Question ID']} / {r['Variant']}":r for r in shown}
    chosen=lookup[st.selectbox('View evaluated question',list(lookup))]
    with st.expander('Question details',expanded=False):
        st.markdown('**'+chosen['Question']+'**')
        st.write('Status',chosen['Evaluation status'])
        st.write('Expected answer / reference facts',chosen['Expected answer'])
        st.write('Generated answer',chosen['Generated answer'])
        row=chosen['_record']
        st.write('Retrieved evidence',row.get('retrieved') or 'No retrieved evidence recorded')
        st.write('Supporting citations',row.get('citations') or 'No citations recorded')
        st.write('Evaluation metrics',{k:row.get(k) for k in ('retrieval_metrics','answer_quality','faithfulness','citation_evaluation','latency')})
        st.write('Validation details',{k:row.get(k) for k in ('compatibility','selection_diagnostics','raw_selection_diagnostics','error_diagnostics','exclusion_reason')})
        st.caption('Reference details are joined only from the dataset whose verified fingerprint matches this saved run.')


@st.cache_data(show_spinner=False)
def _verified_samples(root,report_versions,dataset_versions):
    from src.evaluation.dashboard_reporting import matching_questions
    examples=[]
    for name,_ in report_versions:
        try:run=json.loads(Path(name).read_text(encoding='utf-8'))
        except (OSError,ValueError):continue
        if run.get('source')!='live':continue
        questions=matching_questions(run,[name for name,_ in dataset_versions])
        for record in run.get('records',[]):
            q=questions.get(record['question_id'],{})
            if q.get('source_verified') and record.get('status')=='Completed' and record.get('answer_status')=='answered' and record.get('citations'):
                text=q['question']
                if text not in examples:examples.append(text)
                if len(examples)==5:return examples
    return examples


def sample_questions(root):
    root=Path(root)
    reports=sorted((root/'evaluation/results').glob('*.json'),reverse=True)
    datasets=sorted((root/'evaluation').glob('*ground_truth.json'))
    return _verified_samples(str(root),tuple((str(p),p.stat().st_mtime_ns) for p in reports),
        tuple((str(p),p.stat().st_mtime_ns) for p in datasets))


